#!/usr/bin/env node
/**
 * Generate frontend/src/abi.ts from the reviewed Foundry artifact.
 *
 * This script never writes a deployment manifest: an ACTIVE manifest must only be
 * produced by a real deployment flow and must never be overwritten by a build step.
 */
import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, relative} from 'node:path';
import {fileURLToPath} from 'node:url';
import {keccak256, toHex} from 'viem';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const contracts = join(root, 'contracts');
const artifactPath = join(contracts, 'abi/QiePredictionMarket.artifact.json');
const abiPath = join(contracts, 'abi/QiePredictionMarket.abi.json');
const sourcePath = join(contracts, 'src/QiePredictionMarket.sol');
const outPath = join(root, 'frontend/src/abi.ts');
const resultsDir = join(root, 'results');

const artifactRaw = readFileSync(artifactPath);
const abiRaw = readFileSync(abiPath);
const sourceRaw = readFileSync(sourcePath);
const artifact = JSON.parse(artifactRaw.toString('utf8'));
const abi = JSON.parse(abiRaw.toString('utf8'));

if (!artifact.bytecode?.object || !artifact.deployedBytecode?.object) {
  throw new Error('artifact tidak memuat bytecode/deployedBytecode');
}
if (!artifact.metadata?.settings) {
  throw new Error('artifact tidak memuat metadata.settings');
}

const creationBytecode = artifact.bytecode.object.startsWith('0x')
  ? artifact.bytecode.object
  : `0x${artifact.bytecode.object}`;
const runtimeBytecode = artifact.deployedBytecode.object.startsWith('0x')
  ? artifact.deployedBytecode.object
  : `0x${artifact.deployedBytecode.object}`;

const hashes = {
  creationBytecodeKeccak256: keccak256(creationBytecode),
  runtimeBytecodeKeccak256: keccak256(runtimeBytecode),
  sourceKeccak256: keccak256(sourceRaw),
  settingsKeccak256: keccak256(toHex(JSON.stringify(artifact.metadata.settings))),
  artifactSha256: `0x${createHash('sha256').update(artifactRaw).digest('hex')}`,
  abiSha256: `0x${createHash('sha256').update(abiRaw).digest('hex')}`,
};

const compiler = artifact.metadata?.compiler?.version ?? 'unknown';
const settings = artifact.metadata.settings;

const ts = `// Generated by scripts/gen-abi-ts.mjs from contracts/abi/*.json (Foundry artifact).
// Do not edit by hand. Contract source: contracts/src/QiePredictionMarket.sol
// Compiler: solc ${compiler}; EVM: ${settings.evmVersion}; optimizer: ${
  settings.optimizer?.enabled === true ? 'on' : 'off'
}; bytecodeHash: ${settings.metadata?.bytecodeHash ?? 'unknown'}.
/* eslint-disable */
export const QIE_PREDICTION_MARKET_ABI = ${JSON.stringify(abi)} as const;

export const QIE_PREDICTION_MARKET_CREATION_BYTECODE = ${JSON.stringify(creationBytecode)} as const;

export const QIE_PREDICTION_MARKET_ARTIFACT = {
  creationBytecodeKeccak256: ${JSON.stringify(hashes.creationBytecodeKeccak256)},
  runtimeBytecodeKeccak256: ${JSON.stringify(hashes.runtimeBytecodeKeccak256)},
  sourceKeccak256: ${JSON.stringify(hashes.sourceKeccak256)},
  settingsKeccak256: ${JSON.stringify(hashes.settingsKeccak256)},
  artifactSha256: ${JSON.stringify(hashes.artifactSha256)},
  abiSha256: ${JSON.stringify(hashes.abiSha256)},
  compiler: ${JSON.stringify(compiler)},
  evmVersion: ${JSON.stringify(settings.evmVersion)},
  optimizer: ${settings.optimizer?.enabled === true},
  bytecodeHash: ${JSON.stringify(settings.metadata?.bytecodeHash ?? 'unknown')},
} as const;
`;

writeFileSync(outPath, ts);

const digestLines = [
  `# sha256 of files (reproducible input digests)`,
  `${createHash('sha256').update(sourceRaw).digest('hex')}  ${relative(root, sourcePath)}`,
  `${createHash('sha256').update(artifactRaw).digest('hex')}  ${relative(root, artifactPath)}`,
  `${createHash('sha256').update(abiRaw).digest('hex')}  ${relative(root, abiPath)}`,
  '',
  `# keccak256 of bytecode and compiler settings`,
  `${hashes.creationBytecodeKeccak256}  creationBytecode`,
  `${hashes.runtimeBytecodeKeccak256}  runtimeBytecode`,
  `${hashes.sourceKeccak256}  source`,
  `${hashes.settingsKeccak256}  metadata.settings`,
  '',
  `# sha256 of the generated artifacts`,
  `${hashes.artifactSha256}  artifactSha256`,
  `${hashes.abiSha256}  abiSha256`,
  '',
];
writeFileSync(join(resultsDir, 'digests.txt'), digestLines.join('\n'));
writeFileSync(
  join(resultsDir, 'digests.json'),
  `${JSON.stringify(
    {
      source: relative(root, sourcePath),
      artifact: relative(root, artifactPath),
      abi: relative(root, abiPath),
      compiler,
      evmVersion: settings.evmVersion,
      optimizer: settings.optimizer?.enabled === true,
      bytecodeHash: settings.metadata?.bytecodeHash ?? 'unknown',
      ...hashes,
    },
    null,
    2,
  )}\n`,
);

console.log(`wrote ${relative(root, outPath)}`);
console.log(`creation keccak256 ${hashes.creationBytecodeKeccak256}`);
console.log(`runtime  keccak256 ${hashes.runtimeBytecodeKeccak256}`);
console.log(`source   keccak256 ${hashes.sourceKeccak256}`);
console.log(`settings keccak256 ${hashes.settingsKeccak256}`);
console.log(`artifact sha256    ${hashes.artifactSha256}`);
console.log(`abi      sha256    ${hashes.abiSha256}`);
